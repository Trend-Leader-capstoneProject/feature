    def test_ro07_naive_failed_or_reversed_clocks_block(self):
        class UnconvertibleClock(datetime):
            def astimezone(self, tz=None):
                raise OverflowError("UTC conversion failed")

        for times in ([T0.replace(tzinfo=None)], [ValueError("clock unavailable")],
                      [UnconvertibleClock(2026, 11, 9, tzinfo=timezone.utc)],
                      [T0, T0 - timedelta(seconds=1)], [T0, T0.replace(tzinfo=None)]):
            with self.subTest(times=times):
                self.clock.side_effect = times
                self.assert_blocked(self.observe())
                self.assertFalse(self.out.exists())

