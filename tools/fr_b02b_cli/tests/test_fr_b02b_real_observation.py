def canonical(value):
    return json.dumps(value, ensure_ascii=False, sort_keys=True,
                      separators=(",", ":"), allow_nan=False).encode("utf-8") + b"\n"


class LocalObservationTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name)
        self.archive = self.root / "synthetic.zip"
        self.out = self.root / "observations"
        self.approvals, self.batch = example()
        self.write_zip()
        # An assertion about the missing command is the Red reason, not an
        # import error or a broken mock of a module that does not yet exist.
        help_text = io.StringIO()
        with redirect_stdout(help_text), self.assertRaises(SystemExit):
            run_cli(["--help"])
        self.assertIn("observe-a1-zip", help_text.getvalue(),
                      "Phase 4A observation commands are not implemented")
        self.obs = importlib.import_module("fr_b02b_observation")
        self.addCleanup(patch.stopall)
        self.browser = patch("webbrowser.open", return_value=True).start()
        self.clock = patch.object(self.obs, "utc_now", side_effect=[T0, T0]).start()
        patch("socket.create_connection", side_effect=AssertionError("network forbidden")).start()

    def write_zip(self, approvals_raw=None, batch_raw=None, extra=None):
        with ZipFile(self.archive, "w", compression=ZIP_DEFLATED) as archive:
            archive.writestr(adapter.A1_ZIP_APPROVALS,
                             approvals_raw or canonical(self.approvals))
            archive.writestr(adapter.A1_ZIP_BATCH, batch_raw or canonical(self.batch))
            if extra:
                archive.writestr(*extra)

    def invoke(self, args, answer="YES", input_func=None):
        stdout, stderr = io.StringIO(), io.StringIO()
        with redirect_stdout(stdout), redirect_stderr(stderr):
            try:
                code = run_cli(args, input_func=input_func or (lambda _: answer))
            except SystemExit as exc:
                code = exc.code
        return code, stdout.getvalue(), stderr.getvalue()

    def observe(self, **kwargs):
        return self.invoke(["observe-a1-zip", "--zip", str(self.archive),
                            "--output-dir", str(self.out)], **kwargs)

    def saved(self):
        self.assertEqual(self.observe()[0], 0)
        return next(self.out.glob("LOCAL-OBS-*"))

    def verify(self, folder):
        return self.invoke(["verify-observation", "--zip", str(self.archive),
                            "--record-dir", str(folder)])

    def assert_blocked(self, result):
        self.assertEqual(result[0], 1, result)
        self.assertIn("BLOCKED:", result[2])
        self.assertNotIn("PASS_LOCAL", result[1])
        self.assertNotIn("LOCAL_OBSERVATION_RECORDED_REVIEW_HOLD", result[1])

    def rewrite_record(self, folder, change):
        record_path, index_path = folder / "observation.json", folder / "index.json"
        record = json.loads(record_path.read_bytes())
        change(record)
        raw = canonical(record)
        record_path.write_bytes(raw)
        index = json.loads(index_path.read_bytes())
        index["artifact_sha256"] = "sha256:" + hashlib.sha256(raw).hexdigest()
        index_path.write_bytes(canonical(index))

    def test_ro01_snapshot_is_bound_to_same_zip_and_safe_display_values(self):
        before = self.archive.read_bytes()
        snapshot = adapter.load_a1_snapshot(self.archive)
        self.assertEqual(snapshot.archive_bytes, before)
        for key in ("title", "summary", "source_title", "source_url"):
            self.assertEqual(getattr(snapshot, key), self.batch["items"][0]["content"][key])
        self.assertEqual(snapshot.content_ref, self.approvals["records"][0]["content_ref"])
        self.assertEqual(snapshot.review_evidence_id, "SIM-G4-001")
        self.assertEqual(self.archive.read_bytes(), before)
        self.assertEqual(list(self.root.iterdir()), [self.archive])

    def test_ro02_no_record_before_yes_and_exactly_one_prompt(self):
        calls = []
        def confirm(prompt):
            calls.append(prompt)
            self.browser.assert_called_once_with("https://example.test/release")
            self.assertFalse(self.out.exists())
            self.assertEqual(self.clock.call_count, 0)
            return "YES"
        self.assertEqual(self.observe(input_func=confirm)[0], 0)
        self.assertEqual(len(calls), 1)

    def test_ro03_exact_schemas_canonical_hashes_times_and_hold(self):
        self.clock.side_effect = [T0, T0 + timedelta(seconds=1)]
        before = self.archive.read_bytes()
        folder = self.saved()
        raw = (folder / "observation.json").read_bytes()
        record = json.loads(raw)
        index_raw = (folder / "index.json").read_bytes()
        index = json.loads(index_raw)
        self.assertEqual(set(record), RECORD_KEYS)
        self.assertEqual(set(index), INDEX_KEYS)
        self.assertEqual(raw, canonical(record))
        self.assertEqual(index_raw, canonical(index))
        self.assertEqual(record["schema"], "FR_B02B_LOCAL_OBSERVATION_V1")
        self.assertEqual(index["schema"], "FR_B02B_LOCAL_INDEX_V1")
        self.assertEqual(index["artifact_sha256"], "sha256:" + hashlib.sha256(raw).hexdigest())
        self.assertEqual(record["a1_archive_sha256"], "sha256:" + hashlib.sha256(before).hexdigest())
        self.assertEqual(record["confirmed_at_utc"], "2026-11-09T08:00:00Z")
        self.assertEqual(record["record_created_at_utc"], "2026-11-09T08:00:01Z")
        self.assertEqual(record["event_kind"], "MANUAL_SOURCE_COLLECTION")
        self.assertEqual(record["observation_method"], "HUMAN_BROWSER_ATTESTATION")
        self.assertEqual(record["review_result"], "HOLD")
        self.assertEqual(record["publish_authorization"], "NONE")
        self.assertEqual(record["observer_ref"], "UNVERIFIED_LOCAL_OPERATOR")
        self.assertEqual(record["actor_assurance"], "UNVERIFIED")
        self.assertEqual(record["evidence_id"], folder.name)
        self.assertEqual(uuid.UUID(hex=folder.name.removeprefix("LOCAL-OBS-")).version, 4)
        self.assertEqual(self.archive.read_bytes(), before)
        self.assertEqual(self.verify(folder)[0], 0)
        self.assertIn("PASS_LOCAL_INTEGRITY_ONLY", self.verify(folder)[1])

